import pandas as pd
import numpy as np
import plotly.express as px
df = pd.read_csv('/content/Advertising_F.csv')

px.scatter(df, x='TV', y='radio',
           labels={'TV': 'TV ad spend', 'radio': 'Radio ad spend'})

sales_per_city=df.groupby('City')['sales'].sum().reset_index()
sales_per_city

px.bar(sales_per_city, x='City', y='sales', title='sales per city')

fig = px.scatter_map(
    df,
    lat='latitude',
    lon='longitude',
    size='sales',
    hover_name='City',
    map_style='carto-positron',
    zoom=3
)
fig.show()

